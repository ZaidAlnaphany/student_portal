<?php
// 1. أنشئ مصفوفة تحتوي على أسماء 5 طلاب
$students = ["أحمد", "سارة", "محمد", "ليلى", "خالد"];

// 2. استخدم foreach لطباعة رسالة لكل طالب
foreach ($students as $name) {
    echo "مرحبًا $name, نتمنى لك حظًا سعيدًا في الامتحان!<br>";
}

echo "<hr>";

// 3. استخدم for لطباعة الأعداد من 1 إلى 10
for ($i = 1; $i <= 10; $i++) {
    // 4. استخدم if لتمييز الأعداد الزوجية بلون مختلف
    if ($i % 2 == 0) {
        echo "<span style='color:blue;'>$i</span><br>";
    } else {
        echo "$i<br>";
    }
}

